"""
SQLSimCity asset kits — self-authored procedural geometry for Blender.

Run this from Blender to regenerate `web/src/assets/*.glb`:

    SIMCITY_OUT = r"<repo>/web/src/assets"
    exec(open(r"<repo>/blender/simcity_kit.py").read())

Or headless:

    blender --background --python blender/simcity_kit.py

Why this file exists
--------------------
The repository is Apache-2.0 and `NOTICE` states it "includes no SimCity assets". Every vertex here is
therefore generated by this script from first principles: no downloaded models, no scanned geometry, no
third-party libraries. Checking the generator in rather than only the `.glb` keeps the art auditable and
reproducible — the same script always produces the same mesh.

Evidence boundary
-----------------
Nothing in this file is a measurement. These are the *shells* of the six civic facilities and the street
furniture that dresses the empty ground. The measured quantities — table footprints, table heights, and
the fill of each facility's units — are drawn by the web app as separate geometry positioned in the slots
`web/src/cityFacilityShells.ts` defines. Changing anything here can change how the city looks and can
never change what it claims.

Naming contract
---------------
Every exported mesh is named `<asset>__<role>`. The web app reads the role suffix to pick a material, so
a mesh must always carry one of: `body`, `trim`, `glass`, `metal`, `trunk`, `leaf`, `water`.

Units and orientation
---------------------
Blender is Z-up; the glTF exporter converts to the Y-up the web app uses. Landmarks are built normalised
to a plot radius of 1.0 so the scene can scale them to whatever plot a facility gets. Scenery is built at
world scale, where one unit is roughly one metre, matching the city's building footprints.
"""

import math
import os

import bmesh
import bpy
from mathutils import Euler, Matrix, Vector

# --------------------------------------------------------------------------------------------------
# Mesh building
# --------------------------------------------------------------------------------------------------

ROLES = ("body", "trim", "glass", "metal", "trunk", "leaf", "water")


def _matrix(loc, scale, rot=None):
    translation = Matrix.Translation(Vector(loc))
    rotation = Euler(rot if rot else (0.0, 0.0, 0.0), "XYZ").to_matrix().to_4x4()
    return translation @ rotation @ Matrix.Diagonal(Vector(scale).to_4d())


class Part:
    """One accumulating mesh. Primitives are appended in local space and welded on `build`."""

    def __init__(self):
        self.bm = bmesh.new()

    def box(self, size, loc=(0, 0, 0), rot=None):
        bmesh.ops.create_cube(self.bm, size=1.0, matrix=_matrix(loc, size, rot))
        return self

    def cyl(self, radius_top, radius_bottom, height, loc=(0, 0, 0), rot=None, segments=16):
        bmesh.ops.create_cone(
            self.bm,
            cap_ends=True,
            cap_tris=False,
            segments=segments,
            radius1=radius_bottom,
            radius2=radius_top,
            depth=height,
            matrix=_matrix(loc, (1, 1, 1), rot),
        )
        return self

    def sphere(self, radius, loc=(0, 0, 0), scale=(1, 1, 1), segments=12, rings=8):
        bmesh.ops.create_uvsphere(
            self.bm,
            u_segments=segments,
            v_segments=rings,
            radius=radius,
            matrix=_matrix(loc, scale),
        )
        return self

    def wedge(self, width, depth, height, loc=(0, 0, 0), rot=None):
        """A triangular prism running along X — the gable and saw-tooth workhorse."""
        hw, hd = width / 2.0, depth / 2.0
        verts = [
            (-hw, -hd, 0.0), (hw, -hd, 0.0), (hw, hd, 0.0), (-hw, hd, 0.0),
            (-hw, 0.0, height), (hw, 0.0, height),
        ]
        faces = [(0, 1, 2, 3), (0, 4, 5, 1), (3, 2, 5, 4), (0, 3, 4), (1, 5, 2)]
        self._polyhedron(verts, faces, loc, rot)
        return self

    def ramp(self, width, depth, height, loc=(0, 0, 0), rot=None):
        """A right-angled prism: flat at -Y, rising to `height` at +Y."""
        hw, hd = width / 2.0, depth / 2.0
        verts = [
            (-hw, -hd, 0.0), (hw, -hd, 0.0), (hw, hd, 0.0), (-hw, hd, 0.0),
            (-hw, hd, height), (hw, hd, height),
        ]
        faces = [(0, 1, 2, 3), (3, 2, 5, 4), (0, 4, 5, 1), (0, 3, 4), (1, 5, 2)]
        self._polyhedron(verts, faces, loc, rot)
        return self

    def frustum(self, bottom, top, height, loc=(0, 0, 0), rot=None):
        """A rectangular frustum — plinths, mansards, tapered crowns."""
        bx, by = bottom[0] / 2.0, bottom[1] / 2.0
        tx, ty = top[0] / 2.0, top[1] / 2.0
        verts = [
            (-bx, -by, 0.0), (bx, -by, 0.0), (bx, by, 0.0), (-bx, by, 0.0),
            (-tx, -ty, height), (tx, -ty, height), (tx, ty, height), (-tx, ty, height),
        ]
        faces = [(0, 1, 2, 3), (4, 5, 6, 7), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
        self._polyhedron(verts, faces, loc, rot)
        return self

    def arch(self, width, depth, height, thickness, loc=(0, 0, 0), segments=8):
        """A round-headed opening: two piers carrying a semicircular head."""
        span = width - thickness * 2.0
        pier = height - span / 2.0
        self.box((thickness, depth, pier), (loc[0] - (width - thickness) / 2.0, loc[1], loc[2] + pier / 2.0))
        self.box((thickness, depth, pier), (loc[0] + (width - thickness) / 2.0, loc[1], loc[2] + pier / 2.0))
        inner = span / 2.0
        length = thickness
        for index in range(segments):
            a0 = math.pi * index / segments
            a1 = math.pi * (index + 1) / segments
            mid = (a0 + a1) / 2.0
            self.box(
                (length, depth, (a1 - a0) * (inner + length)),
                (
                    loc[0] + math.cos(mid) * (inner + length / 2.0),
                    loc[1],
                    loc[2] + pier + math.sin(mid) * (inner + length / 2.0),
                ),
                (0.0, -mid, 0.0),
            )
        return self

    def _polyhedron(self, verts, faces, loc, rot):
        matrix = _matrix(loc, (1, 1, 1), rot)
        made = [self.bm.verts.new(matrix @ Vector(v)) for v in verts]
        for face in faces:
            try:
                self.bm.faces.new([made[i] for i in face])
            except ValueError:
                pass
        self.bm.verts.index_update()

    def repeat(self, count, step, fn):
        """Runs `fn(index, offset)` `count` times, stepping `step` between each — colonnades and bays."""
        span = (count - 1) * step / 2.0 if count > 1 else 0.0
        for index in range(count):
            fn(index, index * step - span)
        return self

    def build(self, name, bevel=0.0):
        bmesh.ops.remove_doubles(self.bm, verts=list(self.bm.verts), dist=1e-5)
        if bevel > 0.0:
            bmesh.ops.bevel(
                self.bm,
                geom=list(self.bm.verts) + list(self.bm.edges) + list(self.bm.faces),
                offset=bevel,
                offset_type="OFFSET",
                segments=1,
                profile=0.5,
                affect="EDGES",
                clamp_overlap=True,
            )
        bmesh.ops.recalc_face_normals(self.bm, faces=list(self.bm.faces))
        mesh = bpy.data.meshes.new(name)
        self.bm.to_mesh(mesh)
        self.bm.free()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        return obj


class Asset:
    """One named asset: a bag of `Part`s, one per material role."""

    def __init__(self, name):
        self.name = name
        self.parts = {}

    def __getattr__(self, role):
        if role not in ROLES:
            raise AttributeError(role)
        if role not in self.parts:
            self.parts[role] = Part()
        return self.parts[role]

    def build(self, bevel=0.0):
        return [part.build("%s__%s" % (self.name, role), bevel) for role, part in self.parts.items()]


def clear_scene():
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    for mesh in list(bpy.data.meshes):
        bpy.data.meshes.remove(mesh, do_unlink=True)


