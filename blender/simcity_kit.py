# Civic landmarks
#
# Six silhouettes that have to be told apart at a glance from a shallow overhead camera, which is why
# each one commits to a different roofline: a gantry, a pediment, a saw-tooth, cooling drums, a ridge of
# vaults, and a drum tower. Built normalised to a plot radius of 1.
