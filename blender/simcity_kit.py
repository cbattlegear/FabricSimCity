def export(objects, path):
    for obj in bpy.data.objects:
        obj.select_set(False)
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_materials="NONE",
        # Normals are omitted deliberately: every mesh here is flat-shaded hard surface, so three.js
        # derives face normals in the shader and the buffers come out roughly half the size.
        export_normals=False,
        export_texcoords=False,
        export_tangents=False,
        export_cameras=False,
        export_lights=False,
        export_animations=False,
    )
    total = sum(len(obj.data.vertices) for obj in objects)
    return {
        "path": os.path.basename(path),
        "meshes": len(objects),
        "vertices": total,
        "kib": round(os.path.getsize(path) / 1024.0, 1),
    }


def generate(out_dir):
    reports = []
    clear_scene()
    landmarks = []
    for builder in LANDMARKS:
        landmarks.extend(builder().build(bevel=0.008))
    reports.append(export(landmarks, os.path.join(out_dir, "landmarks.glb")))

    clear_scene()
    scenery = []
    for builder in SCENERY:
        scenery.extend(builder().build(bevel=0.02))
    reports.append(export(scenery, os.path.join(out_dir, "scenery.glb")))

    clear_scene()
    vehicles = []
    # A finer bevel than the scenery kit's 0.02: a bike frame member is 0.06m thick, and 0.02 of
    # bevel rounds it away entirely.
    for builder in VEHICLES:
        vehicles.extend(builder().build(bevel=0.015))
    reports.append(export(vehicles, os.path.join(out_dir, "vehicles.glb")))
    return reports


