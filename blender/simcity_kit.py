def apron(asset, lip=0.055, height=0.05):
    """The kerbed plot every facility stands on, so its ground reads as civic rather than as spill."""
    asset.body.box((2.0, 2.0, height), (0.0, 0.0, height / 2.0))
    for sign in (-1.0, 1.0):
        asset.trim.box((2.0, lip, height * 1.9), (0.0, sign * (1.0 - lip / 2.0), height * 0.95))
        asset.trim.box((lip, 2.0, height * 1.9), (sign * (1.0 - lip / 2.0), 0.0, height * 0.95))
    return asset


