    /// <summary>Whether a character has a glyph, after the upper-casing the renderer applies.</summary>
    public static bool Supports(char character) => Glyphs.ContainsKey(char.ToUpperInvariant(character));

    /// <summary>
    /// The rows of a character's glyph, where <c>'#'</c> is ink. Unknown characters render as a space.
    /// </summary>
    public static string[] Glyph(char character) =>
        Glyphs.TryGetValue(char.ToUpperInvariant(character), out var rows) ? rows : Glyphs[' '];

    /// <summary>Width in pixels of <paramref name="text"/> drawn at <paramref name="scale"/>.</summary>
    public static int Measure(string text, int scale)
    {
        ArgumentNullException.ThrowIfNull(text);
        ArgumentOutOfRangeException.ThrowIfLessThan(scale, 1);
        if (text.Length == 0) return 0;
        return ((GlyphWidth + Tracking) * text.Length - Tracking) * scale;
    }
